"""Regenerate src/jack/script_variants.py from 0xProto's italic Script Variant.

Download 0xProto_2_502.zip from the pinned release, then run:

    uv run python scripts/extract_script_variants.py path/to/0xProto-Italic.ttf
"""

import sys
from pathlib import Path

from fontTools.ttLib import TTFont

CHARS = "fklrsoO"
OUTPUT = Path(__file__).parent.parent / "src/jack/script_variants.py"
WIDTH = 100

HEADER = '''"""0xProto italic Script Variant glyphs used as ss01 by Sotiak Mono.

Generated by scripts/extract_script_variants.py. Source: 0xProto 2.502 Italic
(ss01 Script Variant). Licensed under the SIL Open Font License 1.1.
"""

from typing import TypedDict

SOURCE = "0xProto 2.502 Italic Script Variant"


class ScriptSpec(TypedDict):
    advance: int
    ymax: int
    points: list[list[int]]
    ends: list[int]
    flags: list[int]


SCRIPT_VARIANTS: dict[str, ScriptSpec] = {
'''


def render_list(key, values):
    items = [str(value) for value in values]
    inline = f'        "{key}": [' + ", ".join(items) + "],"
    if len(inline) <= WIDTH:
        return [inline]
    return [f'        "{key}": ['] + [f"            {item}," for item in items] + ["        ],"]


def main(path):
    lines = [HEADER.rstrip("\n")]
    with TTFont(path) as font:
        cmap = font.getBestCmap()
        glyf = font["glyf"]
        for char in CHARS:
            name = cmap[ord(char)] + ".ss01"
            glyph = glyf[name]
            glyph.recalcBounds(glyf)
            points, ends, flags = glyph.getCoordinates(glyf)
            lines.extend(
                [
                    f'    "{char}": {{',
                    f'        "advance": {font["hmtx"][name][0]},',
                    f'        "ymax": {glyph.yMax},',
                    *render_list("points", [list(point) for point in points]),
                    *render_list("ends", list(ends)),
                    *render_list("flags", list(flags)),
                    "    },",
                ]
            )
    lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: extract_script_variants.py path/to/0xProto-Italic.ttf")
    main(sys.argv[1])
