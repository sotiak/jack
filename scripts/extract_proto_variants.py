"""Regenerate src/mono/proto_variants.py from 0xProto's wide-interior glyphs.

Download 0xProto_2_502.zip from the pinned release, then run:

    uv run python scripts/extract_proto_variants.py path/to/0xProto/fonts
"""

import sys
from pathlib import Path

from fontTools.ttLib import TTFont

FACES = {
    "Regular": "0xProto-Regular.ttf",
    "Bold": "0xProto-Bold.ttf",
    "Italic": "0xProto-Italic.ttf",
}
GLYPHS = "vVwWA"
OUTPUT = Path(__file__).parent.parent / "src/mono/proto_variants.py"
WIDTH = 100

HEADER = '''"""0xProto wide-interior glyphs used by Sotiak Mono.

Generated by scripts/extract_proto_variants.py. Source: 0xProto 2.502 Regular,
Bold, and Italic (v/V/w/W/A). Licensed under the SIL Open Font License 1.1.
"""

from typing import TypedDict

SOURCE = "0xProto 2.502 v/V/w/W/A"


class ProtoSpec(TypedDict):
    advance: int
    points: list[list[int]]
    ends: list[int]
    flags: list[int]


PROTO_VARIANTS: dict[str, dict[str, ProtoSpec]] = {
'''


def render_list(key, values):
    items = [str(value) for value in values]
    inline = f'            "{key}": [' + ", ".join(items) + "],"
    if len(inline) <= WIDTH:
        return [inline]
    return (
        [f'            "{key}": [']
        + [f"                {item}," for item in items]
        + ["            ],"]
    )


def render_glyph(char, spec):
    return [
        f'        "{char}": {{',
        f'            "advance": {spec["advance"]},',
        *render_list("points", spec["points"]),
        *render_list("ends", spec["ends"]),
        *render_list("flags", spec["flags"]),
        "        },",
    ]


def main(directory):
    lines = [HEADER.rstrip("\n")]
    for style, face in FACES.items():
        with TTFont(Path(directory) / face) as font:
            cmap = font.getBestCmap()
            glyf = font["glyf"]
            lines.append(f'    "{style}": {{')
            for char in GLYPHS:
                name = cmap[ord(char)]
                glyph = glyf[name]
                points, ends, flags = glyph.getCoordinates(glyf)
                spec = {
                    "advance": font["hmtx"][name][0],
                    "points": [list(point) for point in points],
                    "ends": list(ends),
                    "flags": list(flags),
                }
                lines.extend(render_glyph(char, spec))
            lines.append("    },")
    lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
