"""Regenerate src/mono/glyphs.py from Iosevka's variant glyphs.

The PkgTTF-IosevkaSS03 input has no cv glyphs, so fetch the full package
instead, unzip the four Extended faces, and point this script at them:

    https://github.com/be5invis/Iosevka/releases/download/v34.9.1/PkgTTF-Iosevka-34.9.1.zip
    uv run python scripts/extract_variants.py path/to/unzipped

Glyph names are Iosevka's variant tables (t.cv54-8 etc.). Confirm them again
after an Iosevka upgrade; a renumbered variant would silently change the shape.
"""

import sys
from pathlib import Path

from fontTools.ttLib import TTFont

FACES = {
    "Regular": "Iosevka-Extended.ttf",
    "Bold": "Iosevka-ExtendedBold.ttf",
    "Italic": "Iosevka-ExtendedOblique.ttf",
    "BoldItalic": "Iosevka-ExtendedBoldOblique.ttf",
}
GLYPHS = {"t": "t.cv54-8", "M": "M.cv23-1"}
OUTPUT = Path(__file__).parent.parent / "src/mono/glyphs.py"
WIDTH = 100

HEADER = '''"""Iosevka glyph variants used by the Sotiak Mono build.

Generated by scripts/extract_variants.py. Source: Iosevka 34.9.1 Extended: cv23-1 (hanging serifless M), cv54-8 (flat hook, short neck). Licensed under the SIL Open Font License 1.1.
"""

from typing import TypedDict

SOURCE = "Iosevka 34.9.1 Extended: cv23-1 (hanging serifless M), cv54-8 (flat hook, short neck)"


class GlyphSpec(TypedDict):
    advance: int
    lsb: int
    points: list[list[int]]
    ends: list[int]
    flags: list[int]


VARIANTS: dict[str, dict[str, GlyphSpec]] = {
'''


def render_list(key, values):
    items = [str(value) for value in values]
    inline = f'            "{key}": [' + ", ".join(items) + "],"
    if len(inline) <= WIDTH:
        return [inline]
    return (
        [f'            "{key}": [']
        + [f"                {item}," for item in items]
        + ["            ],"]
    )


def render_glyph(char, spec):
    return [
        f'        "{char}": {{',
        f'            "advance": {spec["advance"]},',
        f'            "lsb": {spec["lsb"]},',
        *render_list("points", spec["points"]),
        *render_list("ends", spec["ends"]),
        *render_list("flags", spec["flags"]),
        "        },",
    ]


def main(directory):
    lines = [HEADER.rstrip("\n")]
    for style, face in FACES.items():
        with TTFont(Path(directory) / face) as font:
            lines.append(f'    "{style}": {{')
            for char, name in GLYPHS.items():
                if name not in font.getGlyphOrder():
                    raise ValueError(f"{face}: missing {name}; check GLYPHS against this Iosevka")
                glyph = font["glyf"][name]
                points, ends, flags = glyph.getCoordinates(font["glyf"])
                spec = {
                    "advance": font["hmtx"][name][0],
                    "lsb": font["hmtx"][name][1],
                    "points": [list(point) for point in points],
                    "ends": list(ends),
                    "flags": list(flags),
                }
                lines.extend(render_glyph(char, spec))
            lines.append("    },")
    lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
